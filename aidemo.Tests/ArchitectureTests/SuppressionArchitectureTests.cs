using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text.RegularExpressions;

namespace aidemo.Tests.ArchitectureTests
{
    /// <summary>
    /// Every suppression in the repo - .NET and web - carries a link to its `suppressions` issue, as
    /// .docs/agents/suppressions.md requires. Scans the source tree, so it runs from the build output.
    /// </summary>
    [TestClass]
    public sealed partial class SuppressionArchitectureTests
    {
        private static readonly HashSet<string> SkippedDirectories = new(StringComparer.OrdinalIgnoreCase)
        {
            ".git", ".vs", "bin", "obj", "node_modules", "coverage", "dist", "TestResults", "Migrations",
        };

        [TestMethod]
        public void Suppressions_Should_Reference_Their_Issue()
        {
            var root = RepoRoot();
            var violations = SourceFiles(root)
                .Where(f => Path.GetFileName(f) != $"{nameof(SuppressionArchitectureTests)}.cs")
                .SelectMany(f => Violations(root, f))
                .ToList();

            Assert.IsEmpty(violations, $"Each suppression needs approval and its own `suppressions` issue, referenced as `issue #<n>` on its line or the line above (.docs/agents/suppressions.md):{Environment.NewLine}{string.Join(Environment.NewLine, violations)}");
        }

        private static IEnumerable<string> Violations(string root, string file)
        {
            var pattern = SuppressionPattern(file);
            if (pattern is null) yield break;

            var lines = File.ReadAllLines(file);
            if (lines.Any(l => l.Contains("<auto-generated", StringComparison.Ordinal))) yield break;

            var inMigrationsSection = false;
            for (var i = 0; i < lines.Length; i++)
            {
                // .editorconfig: the Migrations section's blanket `none` is the policy's generated-code exclusion.
                if (EditorConfigSection().Match(lines[i]) is { Success: true } section)
                    inMigrationsSection = section.Value.Contains("Migrations", StringComparison.Ordinal);
                if (inMigrationsSection) continue;

                if (!pattern.IsMatch(lines[i])) continue;
                if (IssueReference().IsMatch(lines[i]) || (i > 0 && IssueReference().IsMatch(lines[i - 1]))) continue;

                yield return $"  {Path.GetRelativePath(root, file).Replace('\\', '/')}:{i + 1}: {lines[i].Trim()}";
            }
        }

        private static Regex SuppressionPattern(string file)
        {
            var name = Path.GetFileName(file);
            if (name == ".editorconfig") return EditorConfigSuppression();
            if (name == ".oxlintrc.json") return OxlintConfigSuppression();

            return Path.GetExtension(file).ToLowerInvariant() switch
            {
                ".cs" => CSharpSuppression(),
                ".csproj" or ".props" or ".targets" => MsBuildSuppression(),
                ".ts" or ".tsx" or ".js" or ".mjs" or ".css" => LintSuppression(),
                _ => null,
            };
        }

        private static IEnumerable<string> SourceFiles(string directory)
        {
            foreach (var file in Directory.EnumerateFiles(directory))
                yield return file;

            foreach (var child in Directory.EnumerateDirectories(directory).Where(d => !SkippedDirectories.Contains(Path.GetFileName(d))))
            {
                foreach (var file in SourceFiles(child))
                    yield return file;
            }
        }

        private static string RepoRoot()
        {
            var directory = new DirectoryInfo(AppContext.BaseDirectory);
            while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "aidemo.slnx")))
                directory = directory.Parent;

            Assert.IsNotNull(directory, "aidemo.slnx not found above the test output directory.");
            return directory.FullName;
        }

        [GeneratedRegex(@"issue #\d+", RegexOptions.IgnoreCase)]
        private static partial Regex IssueReference();

        [GeneratedRegex(@"^\s*\[.*\]\s*$")]
        private static partial Regex EditorConfigSection();

        [GeneratedRegex(@"#pragma\s+warning\s+disable|#nullable\s+disable|SuppressMessage\s*\(")]
        private static partial Regex CSharpSuppression();

        [GeneratedRegex(@"<NoWarn>")]
        private static partial Regex MsBuildSuppression();

        [GeneratedRegex(@"(oxlint|eslint)-disable")]
        private static partial Regex LintSuppression();

        [GeneratedRegex(@"\.severity\s*=\s*(none|silent|suggestion)\b")]
        private static partial Regex EditorConfigSuppression();

        [GeneratedRegex(@":\s*(""(off|allow)""|0)\s*[,\]}]?")]
        private static partial Regex OxlintConfigSuppression();
    }
}
